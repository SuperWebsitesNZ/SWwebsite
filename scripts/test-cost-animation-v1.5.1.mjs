// Super Websites v1.5.1 | Controlled viewport and animation time; no browser/network.
import assert from 'node:assert/strict';
import {chartIsVisible, createCostAnimation} from '../cost-animation-v1.5.1.js';
const viewport={width:1280,height:700};
const rectangle=top=>({top,bottom:top+200,left:100,right:600,height:200,width:500});
assert.equal(chartIsVisible(rectangle(695),viewport,100),false,'A sliver must not start playback');
assert.equal(chartIsVisible(rectangle(600),viewport,100),false,'Less than 65% visible');
assert.equal(chartIsVisible(rectangle(500),viewport,100),true);
assert.equal(chartIsVisible(rectangle(-50),viewport,100),false,'Sticky header obscures the graph');
assert.equal(chartIsVisible({...rectangle(200),left:1500,right:2000},viewport,100),false);
assert.equal(chartIsVisible({top:100,bottom:1700,height:1600,left:0,right:500,width:500},viewport,100),true,'Oversized graph must still be playable on a short viewport');
let nextId=1, frames=new Map(), rendered=[], state;
const player=createCostAnimation({render:value=>rendered.push(value),onState:value=>state=value,requestFrame:callback=>{const id=nextId++;frames.set(id,callback);return id;},cancelFrame:id=>frames.delete(id),duration:1000});
function step(time){const pending=[...frames.values()];frames.clear();for(const callback of pending)callback(time);}
assert.equal(frames.size,0,'Never start offscreen');
player.setVisibility(true,false);
step(0);step(200);
assert.equal(rendered.at(-1),.2);
player.setVisibility(false,false);
assert.equal(frames.size,0,'Stop immediately on leaving the section');
step(5000);
assert.equal(rendered.at(-1),.2,'No hidden progress');
player.setVisibility(true,false);
step(5000);step(5200);
assert.equal(rendered.at(-1),.4,'Resume rather than restart or count time away');
player.setVisibility(true,true);
assert.equal(frames.size,0,'Tab/intro/form/global pause blocks playback');
step(9000);assert.equal(rendered.at(-1),.4);
player.setVisibility(true,false);
step(9000);step(9100);
player.setVisibility(true,false);
step(9200);
assert.equal(rendered.at(-1),.6,'Repeated visible checks must not reset time');
step(9600);
assert.equal(rendered.at(-1),1);
assert.equal(state.complete,true);
assert.equal(frames.size,0);
player.setVisible(false);player.setVisible(true);
assert.equal(frames.size,0,'Do not auto-replay a completed chart');
player.setVisibility(false,false);player.replay();
assert.equal(rendered.at(-1),0);
assert.equal(frames.size,0,'Replay waits if graph is offscreen');
player.setVisibility(true,false);step(10000);step(10100);
assert.equal(rendered.at(-1),.1);
player.finish();
assert.equal(rendered.at(-1),1,'Reduced motion shows final costs');
assert.equal(frames.size,0);
console.log('Cost animation passed: visible threshold, sticky header, short viewport, offscreen pause/resume, overlay/tab/motion blocking, repeated checks, completion and replay.');
